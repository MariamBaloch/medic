CREATE TABLE availability_rule (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP(6) WITH TIME ZONE,
    updated_at TIMESTAMP(6) WITH TIME ZONE,
    doctor_id BIGINT NOT NULL,
    start_date DATE NOT NULL,
    end_date DATE,
    start_time TIME(6) NOT NULL,
    end_time TIME(6) NOT NULL,
    slot_minutes INTEGER NOT NULL
);
CREATE INDEX idx_availability_rule_doctor_id ON availability_rule (doctor_id);

CREATE TABLE availability_rule_days (
    rule_id BIGINT NOT NULL,
    days_of_week VARCHAR(10) NOT NULL,
    PRIMARY KEY (rule_id, days_of_week),
    CONSTRAINT fk_availability_rule_days_rule FOREIGN KEY (rule_id)
        REFERENCES availability_rule (id) ON DELETE CASCADE
);

CREATE TABLE availability_exception (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP(6) WITH TIME ZONE,
    updated_at TIMESTAMP(6) WITH TIME ZONE,
    doctor_id BIGINT NOT NULL,
    exception_date DATE NOT NULL,
    start_time TIME(6),
    end_time TIME(6),
    reason VARCHAR(255)
);
CREATE INDEX idx_availability_exception_doctor_date ON availability_exception (doctor_id, exception_date);

CREATE TABLE appointment (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP(6) WITH TIME ZONE,
    updated_at TIMESTAMP(6) WITH TIME ZONE,
    doctor_id BIGINT NOT NULL,
    patient_id BIGINT NOT NULL,
    patient_user_id BIGINT NOT NULL,
    doctor_user_id BIGINT NOT NULL,
    patient_name VARCHAR(255) NOT NULL,
    patient_email VARCHAR(255) NOT NULL,
    doctor_name VARCHAR(255) NOT NULL,
    doctor_email VARCHAR(255) NOT NULL,
    doctor_specialization_id BIGINT,
    availability_rule_id BIGINT,
    appointment_date DATE NOT NULL,
    start_time TIME(6) NOT NULL,
    end_time TIME(6) NOT NULL,
    booking_fee NUMERIC(10, 2),
    status VARCHAR(20) NOT NULL,
    reason TEXT,
    cancelled_reason VARCHAR(255),
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT fk_appointment_availability_rule FOREIGN KEY (availability_rule_id) REFERENCES availability_rule (id)
);
CREATE UNIQUE INDEX uq_appointment_active_doctor_slot
    ON appointment (doctor_id, appointment_date, start_time)
    WHERE status <> 'CANCELLED';
CREATE INDEX idx_appointment_patient_date ON appointment (patient_id, appointment_date);
CREATE INDEX idx_appointment_doctor_name ON appointment (doctor_name);
CREATE INDEX idx_appointment_patient_name ON appointment (patient_name);
CREATE INDEX idx_appointment_doctor_specialization ON appointment (doctor_specialization_id);

CREATE TABLE appointment_waitlist_entry (
    id BIGSERIAL PRIMARY KEY,
    patient_id BIGINT NOT NULL,
    doctor_id BIGINT NOT NULL,
    patient_user_id BIGINT NOT NULL,
    doctor_user_id BIGINT NOT NULL,
    patient_name VARCHAR(255) NOT NULL,
    patient_email VARCHAR(255) NOT NULL,
    doctor_name VARCHAR(255) NOT NULL,
    doctor_email VARCHAR(255) NOT NULL,
    doctor_specialization_id BIGINT,
    appointment_date DATE NOT NULL,
    preferred_start_time TIME NOT NULL,
    status VARCHAR(20) NOT NULL,
    offered_at TIMESTAMPTZ,
    offer_expires_at TIMESTAMPTZ,
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_waitlist_status CHECK (status IN ('WAITING', 'OFFERED', 'BOOKED', 'CANCELLED', 'EXPIRED'))
);

CREATE UNIQUE INDEX uq_waitlist_active_patient_slot
    ON appointment_waitlist_entry (patient_id, doctor_id, appointment_date, preferred_start_time)
    WHERE status IN ('WAITING', 'OFFERED');

CREATE UNIQUE INDEX uq_waitlist_active_offer_slot
    ON appointment_waitlist_entry (doctor_id, appointment_date, preferred_start_time)
    WHERE status = 'OFFERED';

CREATE INDEX ix_waitlist_patient_created
    ON appointment_waitlist_entry (patient_id, created_at DESC, id DESC);

CREATE INDEX ix_waitlist_slot_queue
    ON appointment_waitlist_entry (doctor_id, appointment_date, preferred_start_time, created_at, id)
    WHERE status = 'WAITING';

CREATE INDEX ix_waitlist_expired_offers
    ON appointment_waitlist_entry (offer_expires_at)
    WHERE status = 'OFFERED';

CREATE INDEX idx_waitlist_doctor_name ON appointment_waitlist_entry (doctor_name);

CREATE TABLE outbox_event (
    id              BIGSERIAL PRIMARY KEY,
    event_id        VARCHAR(36)  NOT NULL,
    aggregate_type  VARCHAR(64)  NOT NULL,
    aggregate_id    VARCHAR(64)  NOT NULL,
    event_type      VARCHAR(128) NOT NULL,
    payload         TEXT         NOT NULL,
    correlation_id  VARCHAR(128),
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    published_at    TIMESTAMPTZ,
    attempts        INT          NOT NULL DEFAULT 0,
    CONSTRAINT uq_outbox_event_id UNIQUE (event_id)
);

CREATE INDEX idx_outbox_unpublished
    ON outbox_event (id)
    WHERE published_at IS NULL;
