CREATE TABLE roles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP(6) WITH TIME ZONE,
    updated_at TIMESTAMP(6) WITH TIME ZONE,
    name VARCHAR(255) NOT NULL,
    CONSTRAINT uk_roles_name UNIQUE (name)
);

CREATE TABLE specializations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP(6) WITH TIME ZONE,
    updated_at TIMESTAMP(6) WITH TIME ZONE,
    name VARCHAR(100) NOT NULL,
    description TEXT,
    CONSTRAINT uk_specializations_name UNIQUE (name)
);

CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP(6) WITH TIME ZONE,
    updated_at TIMESTAMP(6) WITH TIME ZONE,
    role_id BIGINT NOT NULL,
    email VARCHAR(255) NOT NULL,
    password VARCHAR(255) NOT NULL,
    image_url VARCHAR(255),
    first_name VARCHAR(100) NOT NULL,
    last_name VARCHAR(100) NOT NULL,
    date_of_birth DATE NOT NULL,
    phone VARCHAR(20) NOT NULL,
    gender VARCHAR(20),
    verification_token VARCHAR(255),
    token_expiry TIMESTAMP(6),
    status VARCHAR(20) NOT NULL,
    deleted_at TIMESTAMP(6) WITH TIME ZONE,
    reset_password_token VARCHAR(255),
    reset_password_token_expiry TIMESTAMP(6),
    CONSTRAINT uk_users_email UNIQUE (email),
    CONSTRAINT fk_users_role FOREIGN KEY (role_id) REFERENCES roles (id)
);
CREATE INDEX idx_users_role_id ON users (role_id);

CREATE TABLE doctor_profiles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP(6) WITH TIME ZONE,
    updated_at TIMESTAMP(6) WITH TIME ZONE,
    user_id BIGINT NOT NULL,
    specialization_id BIGINT NOT NULL,
    license_number VARCHAR(100) NOT NULL,
    qualification VARCHAR(255),
    years_of_experience INTEGER,
    consultation_fee NUMERIC(10, 2),
    hospital_affiliation VARCHAR(255),
    clinic_address VARCHAR(255),
    bio TEXT,
    is_verified BOOLEAN NOT NULL,
    CONSTRAINT uk_doctor_profiles_user_id UNIQUE (user_id),
    CONSTRAINT uk_doctor_profiles_license_number UNIQUE (license_number),
    CONSTRAINT fk_doctor_profiles_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT fk_doctor_profiles_specialization FOREIGN KEY (specialization_id) REFERENCES specializations (id)
);
CREATE INDEX idx_doctor_profiles_specialization_id ON doctor_profiles (specialization_id);

CREATE TABLE patient_profile (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP(6) WITH TIME ZONE,
    updated_at TIMESTAMP(6) WITH TIME ZONE,
    user_id BIGINT NOT NULL,
    address VARCHAR(255),
    city VARCHAR(100),
    country VARCHAR(100),
    blood_type VARCHAR(20),
    height_cm INTEGER,
    weight_kg INTEGER,
    allergies TEXT,
    chronic_conditions TEXT,
    CONSTRAINT uk_patient_profile_user_id UNIQUE (user_id),
    CONSTRAINT fk_patient_profile_user FOREIGN KEY (user_id) REFERENCES users (id)
);

CREATE TABLE availability_rule (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP(6) WITH TIME ZONE,
    updated_at TIMESTAMP(6) WITH TIME ZONE,
    doctor_id BIGINT NOT NULL,
    start_date DATE NOT NULL,
    end_date DATE,
    start_time TIME(6) NOT NULL,
    end_time TIME(6) NOT NULL,
    slot_minutes INTEGER NOT NULL,
    CONSTRAINT fk_availability_rule_doctor FOREIGN KEY (doctor_id) REFERENCES doctor_profiles (id)
);
CREATE INDEX idx_availability_rule_doctor_id ON availability_rule (doctor_id);

CREATE TABLE availability_rule_days (
    rule_id BIGINT NOT NULL,
    days_of_week VARCHAR(10) NOT NULL,
    PRIMARY KEY (rule_id, days_of_week),
    CONSTRAINT fk_availability_rule_days_rule FOREIGN KEY (rule_id)
        REFERENCES availability_rule (id) ON DELETE CASCADE
);

CREATE TABLE availability_exception (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP(6) WITH TIME ZONE,
    updated_at TIMESTAMP(6) WITH TIME ZONE,
    doctor_id BIGINT NOT NULL,
    exception_date DATE NOT NULL,
    start_time TIME(6),
    end_time TIME(6),
    reason VARCHAR(255),
    CONSTRAINT fk_availability_exception_doctor FOREIGN KEY (doctor_id) REFERENCES doctor_profiles (id)
);
CREATE INDEX idx_availability_exception_doctor_date ON availability_exception (doctor_id, exception_date);

CREATE TABLE appointment (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP(6) WITH TIME ZONE,
    updated_at TIMESTAMP(6) WITH TIME ZONE,
    doctor_id BIGINT NOT NULL,
    patient_id BIGINT NOT NULL,
    availability_rule_id BIGINT,
    appointment_date DATE NOT NULL,
    start_time TIME(6) NOT NULL,
    end_time TIME(6) NOT NULL,
    booking_fee NUMERIC(10, 2),
    status VARCHAR(20) NOT NULL,
    reason TEXT,
    cancelled_reason VARCHAR(255),
    CONSTRAINT uc_appointment_doctor_date_time UNIQUE (doctor_id, appointment_date, start_time),
    CONSTRAINT fk_appointment_doctor FOREIGN KEY (doctor_id) REFERENCES doctor_profiles (id),
    CONSTRAINT fk_appointment_patient FOREIGN KEY (patient_id) REFERENCES patient_profile (id),
    CONSTRAINT fk_appointment_availability_rule FOREIGN KEY (availability_rule_id) REFERENCES availability_rule (id)
);
CREATE INDEX idx_appointment_patient_date ON appointment (patient_id, appointment_date);

CREATE TABLE notification (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP(6) WITH TIME ZONE,
    updated_at TIMESTAMP(6) WITH TIME ZONE,
    type VARCHAR(255) NOT NULL,
    action VARCHAR(255) NOT NULL,
    user_id BIGINT NOT NULL,
    title VARCHAR(255) NOT NULL,
    message VARCHAR(255) NOT NULL,
    read BOOLEAN NOT NULL,
    related_entity_id BIGINT,
    CONSTRAINT fk_notification_user FOREIGN KEY (user_id) REFERENCES users (id)
);
CREATE INDEX idx_notification_user_id ON notification (user_id);

CREATE TABLE audit_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(255) NOT NULL,
    action VARCHAR(255) NOT NULL,
    entity_type VARCHAR(255) NOT NULL,
    description VARCHAR(255) NOT NULL,
    timestamp TIMESTAMP(6) NOT NULL
);
